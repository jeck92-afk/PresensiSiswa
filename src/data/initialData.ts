export const DEFAULT_CLASSES = ['X IPAS', 'XI IPAS', 'XII IPAS'] as const;

export const normalizeClassName = (cls: string): string => {
  if (!cls) return 'X IPAS';
  const trimmed = cls.trim();
  const upper = trimmed.toUpperCase();
  if (upper.startsWith('XII') || upper.includes('12')) return 'XII IPAS';
  if (upper.startsWith('XI') || upper.includes('11')) return 'XI IPAS';
  if (upper.startsWith('X') || upper.includes('10')) return 'X IPAS';
  return trimmed;
};

